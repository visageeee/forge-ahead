using System;
using System.Collections.Generic;
using System.Linq;
using System.Xml.Linq;

namespace Weland
{
    public sealed class MmlFog
    {
        // Include=false leaves the scenario's existing fog alone.
        public bool Include;
        public bool Enabled;
        public bool Landscapes = true;
        public double Depth = 8;
        public double Red = 0.5, Green = 0.5, Blue = 0.5;

        internal XElement ToXml(int type)
        {
            if (!Include) return null;
            if (!double.IsFinite(Depth) || Depth <= 0)
                throw new ArgumentException("Fog depth must be greater than zero.");
            foreach (double value in new[] { Red, Green, Blue })
                if (!double.IsFinite(value) || value < 0 || value > 1)
                    throw new ArgumentException("Fog color components must be between 0 and 1.");
            return new XElement("fog", new XAttribute("type", type),
                new XAttribute("on", Enabled), new XAttribute("depth", Depth),
                new XAttribute("landscapes", Landscapes),
                new XElement("color", new XAttribute("red", Red),
                    new XAttribute("green", Green), new XAttribute("blue", Blue)));
        }
    }

    public sealed class LevelMml
    {
        public const int KeepCollection = -2;
        public int Environment;
        // Seven engine slots. -2 leaves that slot unchanged; -1 clears it.
        public int[] Collections = Enumerable.Repeat(KeepCollection, 7).ToArray();
        public bool IncludeCollections;
        public MmlFog Above = new MmlFog();
        public MmlFog Below = new MmlFog();

        public static int[] TextureCollections(Level level)
        {
            var result = new SortedSet<int>();
            void Add(ShapeDescriptor shape) { if (!shape.IsEmpty()) result.Add(shape.Collection); }
            foreach (var polygon in level.Polygons) { Add(polygon.FloorTexture); Add(polygon.CeilingTexture); }
            foreach (var side in level.Sides) {
                Add(side.Primary.Texture); Add(side.Secondary.Texture); Add(side.Transparent.Texture);
            }
            return result.ToArray();
        }

        public static LevelMml ForLevel(Level level)
        {
            var options = new LevelMml { Environment = level.Environment };
            // Preserve the scenario's first three slots (M1 needs all three).
            // Standard M2/Infinity landscapes are loaded separately by the engine.
            var extra = TextureCollections(level).Where(c => c != 17 + level.Environment && c < 27).ToArray();
            if (extra.Length <= 4)
                for (int i = 0; i < extra.Length; ++i) options.Collections[i + 3] = extra[i];
            options.IncludeCollections = extra.Length > 0 && extra.Length <= 4;
            return options;
        }

        public XDocument Build()
        {
            var root = new XElement("marathon");
            if (IncludeCollections) {
                if (Environment < 0 || Environment > 4)
                    throw new ArgumentException("Texture environment must be between 0 and 4.");
                if (Collections == null || Collections.Length != 7)
                    throw new ArgumentException("Aleph One requires seven texture collection slots.");
                var loading = new XElement("texture_loading");
                for (int i = 0; i < Collections.Length; ++i) {
                    int collection = Collections[i];
                    if (collection < KeepCollection || collection >= ShapeDescriptor.MaximumCollections)
                        throw new ArgumentException("Collection IDs must be between 0 and 31, -1 (empty), or -2 (keep).");
                    if (collection != KeepCollection)
                        loading.Add(new XElement("texture_env", new XAttribute("index", Environment),
                            new XAttribute("which", i), new XAttribute("coll", collection)));
                }
                if (loading.HasElements) root.Add(loading);
            }
            var rendering = new XElement("opengl", Above.ToXml(0), Below.ToXml(1));
            if (rendering.HasElements) root.Add(rendering);
            if (!root.HasElements) throw new ArgumentException("Choose a collection slot or include fog settings before exporting.");
            return new XDocument(new XDeclaration("1.0", "utf-8", null),
                new XComment(" Generated by Forge Ahead. External MML affects every level using this environment; fog affects every level while this script is loaded. "), root);
        }
    }
}
